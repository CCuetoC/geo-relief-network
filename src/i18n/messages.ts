export type MessageKey = keyof typeof messages.en;
export type MessageParams = Record<string, string | number>;

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  const template = messages[locale][key] ?? messages.en[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function dictionaryKeys(locale: Locale): string[] {
  return Object.keys(messages[locale]);
}

export function notificationMessage(
  locale: Locale,
  eventType: string,
  payload: Record<string, unknown>,
): string {
  if (typeof payload.quantity !== "number" || typeof payload.pointName !== "string") {
    return translate(locale, "notification.generic");
  }
  const quantity = formatNumber(locale, Number(payload.quantity ?? 0));
  const productNames = payload.productNames && typeof payload.productNames === "object"
    ? payload.productNames as Record<string, unknown>
    : {};
  const product = typeof productNames[locale] === "string"
    ? String(productNames[locale])
    : typeof payload.productName === "string" ? payload.productName : "";
  if (!product) return translate(locale, "notification.generic");
  const point = typeof payload.pointName === "string" ? payload.pointName : "";
  const expiresAt = typeof payload.expiresAt === "string" ? payload.expiresAt : "";
  const timeZone = typeof payload.timeZone === "string" ? payload.timeZone : undefined;
  const expires = expiresAt ? formatTime(locale, expiresAt, timeZone) : "";
  if (eventType === "FIFO_OFFER_CREATED") {
    return translate(locale, "notification.offer", { quantity, product, point, expires });
  }
  if (eventType === "PHYSICAL_PICKUP_CONFIRMED") {
    return translate(locale, "notification.pickup", { quantity, product, point });
  }
  return translate(locale, "notification.generic");
}
